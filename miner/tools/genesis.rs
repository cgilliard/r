//! Builds the genesis block and writes it to `src/genesis_data.rs`.
//!
//! By default it fetches the latest Bitcoin block from mempool.space (with
//! `curl`, which must be installed): first the tip's height, then the hash
//! at that height, so the two match. The genesis header commits to both and
//! takes the current time.
//!
//! ```text
//! cargo run --release --bin genesis
//! cargo run --release --bin genesis -- --btc-hash <HEX> --btc-height <N> [--time <UNIX>]
//! ```
//!
//! Rebuild afterwards: the chain's genesis is compiled in.

use std::process::{Command, ExitCode};
use std::time::{SystemTime, UNIX_EPOCH};

use r::genesis;

const API: &str = "https://mempool.space/api";

const USAGE: &str = "\
Usage: genesis [--btc-hash <HEX> --btc-height <N>] [--time <UNIX>]

Builds the genesis block, committing to a Bitcoin block (by default the
latest, fetched from mempool.space with curl), and writes
src/genesis_data.rs.";

fn fetch(path: &str) -> Result<String, String> {
    let url = format!("{API}{path}");
    let out = Command::new("curl")
        .args(["-sSf", "--max-time", "30", &url])
        .output()
        .map_err(|e| format!("running curl: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "fetching {url}: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        ));
    }
    String::from_utf8(out.stdout)
        .map(|s| s.trim().to_string())
        .map_err(|_| format!("{url} returned non-UTF-8"))
}

fn run() -> Result<(), String> {
    let mut args = std::env::args().skip(1);
    let (mut hash, mut height, mut time) = (None, None, None);
    while let Some(arg) = args.next() {
        let mut value = || args.next().ok_or(format!("{arg} needs a value"));
        match arg.as_str() {
            "--btc-hash" => hash = Some(value()?),
            "--btc-height" => {
                height = Some(value()?.parse::<u64>().map_err(|_| "bad --btc-height")?)
            }
            "--time" => time = Some(value()?.parse::<u64>().map_err(|_| "bad --time")?),
            "-h" | "--help" => {
                println!("{USAGE}");
                return Ok(());
            }
            _ => return Err(format!("unexpected argument '{arg}'\n\n{USAGE}")),
        }
    }

    let (hash, height) = match (hash, height) {
        (Some(h), Some(n)) => (h, n),
        (None, None) => {
            let height: u64 = fetch("/blocks/tip/height")?
                .parse()
                .map_err(|_| "bad tip height")?;
            let hash = fetch(&format!("/block-height/{height}"))?;
            println!("latest Bitcoin block: {height} {hash}");
            (hash, height)
        }
        _ => return Err("give both --btc-hash and --btc-height, or neither".into()),
    };
    let bytes = genesis::parse_hash(&hash).ok_or(format!("not a block hash: {hash}"))?;
    let hash = hash.to_ascii_lowercase();
    let time = match time {
        Some(t) => t,
        None => SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map_err(|e| e.to_string())?
            .as_secs(),
    };

    let header = genesis::build(&bytes, height, time);
    let header_hash = genesis::hex(&header.hash());
    let source = format!(
        "// Generated by `cargo run --release --bin genesis`; don't edit.

/// The Bitcoin block the genesis commits to: its hash, as usually displayed.
pub const BITCOIN_HASH: &str = \"{hash}\";
/// That block's height.
pub const BITCOIN_HEIGHT: u64 = {height};
/// The genesis time, in seconds since the Unix epoch.
pub const TIMESTAMP: u64 = {time};
/// The genesis header's hash (hex of `hash::to_bytes`), as a check.
pub const HASH: &str = \"{header_hash}\";
"
    );
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/src/genesis_data.rs");
    std::fs::write(path, source).map_err(|e| format!("writing {path}: {e}"))?;
    println!("genesis {header_hash}");
    println!("  commits to Bitcoin block {height} {hash}");
    println!("  (see https://mempool.space/block/{hash})");
    println!("  time {time}, empty state, no reward");
    println!("wrote {path}; rebuild to use it");
    Ok(())
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}
